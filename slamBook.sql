CREATE DATABASE IF NOT EXISTS slamBook CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE slamBook;

CREATE TABLE IF NOT EXISTS adminUsers (
  adminId INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  userName VARCHAR(80) NOT NULL UNIQUE,
  passwordHash VARCHAR(255) NOT NULL,
  status ENUM('active', 'inactive') NOT NULL DEFAULT 'active',
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS slamMemories (
  memoryId INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  writerName VARCHAR(120) NOT NULL,
  relationType VARCHAR(40) NOT NULL,
  dateOfBirth DATE NOT NULL,
  photoPath VARCHAR(255) NOT NULL,
  nickName VARCHAR(120) NOT NULL,
  firstImpression VARCHAR(180) NOT NULL,
  favoriteMemory TEXT NOT NULL,
  learnedThing TEXT NOT NULL,
  futureMessage TEXT NOT NULL,
  contactInfo VARCHAR(180) NOT NULL,
  batchYear VARCHAR(30) NOT NULL,
  createdAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updatedAt TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idxRelationType (relationType),
  INDEX idxCreatedAt (createdAt)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
